# 문제2)
# 국어, 영어, 수학 점수를 콤마로 구분해서 입력 받고
국어 = 90
영어 = 85
수학 = 77
print(국어,영어,수학, sep=',')
총점 = 국어+영어+수학
print(f'총점 {국어+영어+수학}, 평균 {(총점)/3}')
# 총점과 평균(소수점 둘째 자리까지)을 출력하세요.
# 입력 예) 90,85,77
# 출력 예) 총점 252, 평균 84.0

# 문제3)
# 초(second)를 입력 받아서 '몇 시간 몇 분 몇 초' 로 출력하세요.
second = 3725
hours = second // 3600
minutes = (second % 3600) // 60
seconds = second % 60
print(f"{hours}시간 {minutes}분 {seconds}초")
# 입력 예) 3725
# 출력 예) 1시간 2분 5초

